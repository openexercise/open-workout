// Generates src/v1.d.ts from the Lifterclub API's OpenAPI document.
//
// The document lives in the Lifterclub repository (docs/openapi/v1.yaml), the source of truth,
// and is published next to this package in openexercise/open-workout as api/v1.yaml. SPEC
// names another copy.
//
// The Workout schema is the Open Workout Schema document, whose sub-schemas live under $defs.
// openapi-typescript lifts those into components (source, entry, set…) but also emits $defs as
// a required property of Workout, so it's dropped here before conversion.
import { existsSync } from 'node:fs'
import { writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'

const candidates = [
  process.env.SPEC ? pathToFileURL(process.env.SPEC) : undefined,
  new URL('../../../docs/openapi/v1.yaml', import.meta.url),
  new URL('../../../api/v1.yaml', import.meta.url),
].filter((c) => c !== undefined)
const spec = candidates.find((c) => existsSync(c))
if (!spec) {
  console.error('no OpenAPI document found; set SPEC to a copy of v1.yaml')
  process.exit(1)
}

const ast = await openapiTS(spec, {
  transform(schemaObject) {
    if (schemaObject && typeof schemaObject === 'object' && '$defs' in schemaObject) {
      delete schemaObject.$defs
    }
    return undefined
  },
})
const out = new URL('../src/v1.d.ts', import.meta.url)
const header = `/**\n * This file was auto-generated by scripts/gen.mjs from the Lifterclub API's OpenAPI document.\n * Do not make direct changes to the file.\n */\n\n`
await writeFile(out, header + astToString(ast))
console.log(`wrote ${out.pathname}`)
